import fs from 'node:fs/promises';
import OpenCC from 'opencc-js';
const toHant=OpenCC.Converter({from:'cn',to:'tw'}),toHans=OpenCC.Converter({from:'tw',to:'cn'});
let hans='',hant='';
for(const [start,end] of [[0x3400,0x9fff],[0xf900,0xfaff],[0x20000,0x323af]])for(let code=start;code<=end;code++){
 const c=String.fromCodePoint(code);if(toHant(c)!==c)hans+=c;if(toHans(c)!==c)hant+=c;
}
await fs.writeFile('src/shared/chinese-script-data.json',JSON.stringify({hans,hant})+'\n');
await fs.mkdir('public/chinese-script-data',{recursive:true});
await fs.copyFile('node_modules/opencc-js/LICENSES/Apache-2.0.txt','public/chinese-script-data/LICENSE.txt');
await fs.writeFile('public/chinese-script-data/NOTICE.txt','Chinese script identity character sets\nDerived from opencc-js 1.4.2 / opencc-data (https://github.com/nk2028/opencc-data), Apache-2.0.\nGenerated by scripts/generate-chinese-script-data.mjs. Only sets of characters whose isolated conversion changes are retained; no text conversion runs during translation.\n');
console.log(JSON.stringify({hans:[...hans].length,hant:[...hant].length}));
